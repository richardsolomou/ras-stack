import { lstat, readFile } from 'node:fs/promises'
import { join } from 'node:path'

interface PullRequest {
  state: string
  user: { login: string }
  head: { sha: string; ref: string; repo: { full_name: string } | null }
}

export async function managedCommit(repository: string, pr: PullRequest, expectedHeadOid: string, directory: string) {
  if (pr.state !== 'open' || pr.user.login !== 'dependabot[bot]' || pr.head.repo?.full_name !== repository)
    throw new Error('Only open, same-repository Dependabot pull requests can be updated')
  if (pr.head.sha !== expectedHeadOid) throw new Error('The dependency branch changed during regeneration; retry on the current head')

  const additions = await Promise.all(
    ['.pnpmfile.cjs', 'pnpm-lock.yaml'].map(async (path) => {
      const file = join(directory, path)
      if (!(await lstat(file)).isFile()) throw new Error(`${path} must be a regular file`)
      const contents = await readFile(file)
      if (contents.length === 0 || contents.length > 20 * 1024 * 1024) throw new Error(`${path} has an invalid size`)
      if (path === '.pnpmfile.cjs' && !contents.toString().startsWith('// Generated by ras install.'))
        throw new Error('The pnpm hook must be generated by RAS')
      return { path, contents: contents.toString('base64') }
    }),
  )
  return {
    branch: { repositoryNameWithOwner: repository, branchName: pr.head.ref },
    expectedHeadOid,
    message: { headline: 'chore(deps): refresh managed ras installation' },
    fileChanges: { additions },
  }
}
