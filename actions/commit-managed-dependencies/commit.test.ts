import { mkdtemp, symlink, writeFile } from 'node:fs/promises'
import { tmpdir } from 'node:os'
import { join } from 'node:path'
import { describe, expect, it } from 'vitest'
import { managedCommit } from './commit.js'

const repository = 'example/application'
const head = 'a'.repeat(40)
const pr = {
  state: 'open',
  user: { login: 'dependabot[bot]' },
  head: { sha: head, ref: 'dependabot/npm_and_yarn/ras-stack-5.1.0', repo: { full_name: repository } },
}

async function files() {
  const directory = await mkdtemp(join(tmpdir(), 'ras-managed-commit-'))
  await writeFile(join(directory, '.pnpmfile.cjs'), '// Generated by ras install.\nmodule.exports = {}\n')
  await writeFile(join(directory, 'pnpm-lock.yaml'), 'lockfileVersion: 9.0\n')
  return directory
}

describe('managed dependency commits', () => {
  it('commits only the two generated files with an atomic expected-head constraint', async () => {
    const directory = await files()
    await writeFile(join(directory, 'package.json'), 'untrusted extra file')

    expect(await managedCommit(repository, pr, head, directory)).toEqual({
      branch: { repositoryNameWithOwner: repository, branchName: pr.head.ref },
      expectedHeadOid: head,
      message: { headline: 'chore(deps): refresh managed ras installation' },
      fileChanges: {
        additions: [
          { path: '.pnpmfile.cjs', contents: Buffer.from('// Generated by ras install.\nmodule.exports = {}\n').toString('base64') },
          { path: 'pnpm-lock.yaml', contents: Buffer.from('lockfileVersion: 9.0\n').toString('base64') },
        ],
      },
    })
  })

  it('rejects a head changed during regeneration', async () => {
    await expect(managedCommit(repository, { ...pr, head: { ...pr.head, sha: 'b'.repeat(40) } }, head, await files())).rejects.toThrow(
      'branch changed',
    )
  })

  it.each([
    { ...pr, state: 'closed' },
    { ...pr, user: { login: 'another-user' } },
    { ...pr, head: { ...pr.head, repo: { full_name: 'another/application' } } },
    { ...pr, head: { ...pr.head, repo: null } },
  ])('rejects ineligible pull requests: %j', async (request) => {
    await expect(managedCommit(repository, request, head, await files())).rejects.toThrow('same-repository Dependabot')
  })

  it('rejects consumer-owned hooks', async () => {
    const directory = await files()
    await writeFile(join(directory, '.pnpmfile.cjs'), 'module.exports = {}')

    await expect(managedCommit(repository, pr, head, directory)).rejects.toThrow('must be generated by RAS')
  })

  it('rejects a symbolic link', async () => {
    const directory = await mkdtemp(join(tmpdir(), 'ras-managed-symlink-'))
    const original = await files()
    await symlink(join(original, '.pnpmfile.cjs'), join(directory, '.pnpmfile.cjs'))
    await writeFile(join(directory, 'pnpm-lock.yaml'), 'lockfileVersion: 9.0\n')

    await expect(managedCommit(repository, pr, head, directory)).rejects.toThrow('must be a regular file')
  })

  it('rejects empty generated files', async () => {
    const directory = await files()
    await writeFile(join(directory, 'pnpm-lock.yaml'), '')

    await expect(managedCommit(repository, pr, head, directory)).rejects.toThrow('invalid size')
  })
})
