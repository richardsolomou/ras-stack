import { join } from 'node:path'
import { mkdir, readFile, rm } from 'node:fs/promises'
import { exists, json, readJson, writeAtomic } from './files.js'
import type { InstallationPlan } from './plan.js'

export const environmentMarker = '# Generated by RAS.\n*\n'

export function environmentFiles(plan: InstallationPlan): Record<string, string> {
  const files: Record<string, string> = { '.gitignore': environmentMarker }
  const packages = { ...plan.dependencies, ...plan.devDependencies }
  if (plan.presets.typescript) {
    files['tsconfig.json'] = json({
      extends: `../node_modules/ras-stack/config/typescript/${plan.presets.typescript}.json`,
      include: ['../src', '../ras.config.ts'],
      exclude: ['../node_modules', '.'],
    })
  }
  if (plan.presets.oxlint.length) {
    files['oxlint.json'] = json({
      extends: plan.presets.oxlint.map(
        (preset) => `../node_modules/ras-stack/config/${preset === 'base' ? 'oxlint.json' : `oxlint/${preset}.json`}`,
      ),
    })
  }
  if (packages.typescript)
    files['vscode-settings.json'] = json({
      'typescript.tsdk': 'node_modules/typescript/lib',
      'typescript.enablePromptUseWorkspaceTsdk': true,
    })
  return files
}

export async function prepareEnvironment(root: string, plan: InstallationPlan): Promise<void> {
  const directory = join(root, '.ras')
  await mkdir(directory, { recursive: true })
  const files = environmentFiles(plan)
  await Promise.all(
    ['.gitignore', 'tsconfig.json', 'oxlint.json', 'vscode-settings.json'].map(async (file) => {
      const path = join(directory, file)
      const expected = files[file]
      if (!expected) {
        await rm(path, { force: true })
        return
      }
      const actual = (await exists(path)) ? await readFile(path, 'utf8') : undefined
      if (actual === expected) return
      await writeAtomic(path, expected)
    }),
  )
}

export async function commandPath(directory: string, packageName: string, bin: string): Promise<string> {
  const root = join(directory, 'node_modules', packageName)
  const manifest = await readJson<{ bin?: string | Record<string, string> }>(join(root, 'package.json'))
  const target = typeof manifest.bin === 'string' ? manifest.bin : manifest.bin?.[bin]
  if (!target || target.includes('..') || target.startsWith('/'))
    throw new Error(`${packageName} does not publish a safe ${bin} executable`)
  return join(root, target)
}
