import { json } from './files.js'
import type { InstallationPlan } from './plan.js'

export const hookMarker = '// Generated by ras install. Commit this file with ras.lock and pnpm-lock.yaml.\n'

export function pnpmHook(plan: InstallationPlan): string {
  return `${hookMarker}const dependencies = ${json(plan.dependencies).trim()};
const allowBuilds = ${JSON.stringify(plan.allowBuilds)};
module.exports = {
  hooks: {
    updateConfig(config) {
      for (const [name, version] of Object.entries(dependencies)) {
        if (config.overrides?.[name] && config.overrides[name] !== version) {
          throw new Error('Consumer override conflicts with managed ' + name)
        }
      }
      for (const name of allowBuilds) {
        if (config.allowBuilds?.[name] === false) throw new Error('Consumer build policy denies ' + name)
      }
      return {
        ...config,
        publicHoistPattern: [...new Set([...(config.publicHoistPattern ?? []), ...Object.keys(dependencies)])],
        overrides: { ...config.overrides, ...dependencies },
        allowBuilds: { ...Object.fromEntries(Object.keys(dependencies).map(name => [name, false])), ...config.allowBuilds, ...Object.fromEntries(allowBuilds.map(name => [name, true])) },
      }
    },
    readPackage(pkg) {
      if (pkg.name === 'ras-stack') {
        pkg.dependencies = { ...pkg.dependencies, ...dependencies }
        for (const name of Object.keys(dependencies)) {
          if (pkg.peerDependencies) delete pkg.peerDependencies[name]
          if (pkg.peerDependenciesMeta) delete pkg.peerDependenciesMeta[name]
        }
      }
      return pkg
    },
  },
};
`
}
